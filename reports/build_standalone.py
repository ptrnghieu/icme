"""Builds reports/F1_CONSTRUCT_report_standalone.md from reports/F1_CONSTRUCT_paper.md: display formulas and figures become
embedded PNG images (base64), inline math becomes Unicode/HTML, so the single file renders in any markdown previewer.
Usage: python3 build_standalone.py <dir with eq1..eqN.png and fig*.png rendered at 2x>"""
import base64, os, re, struct, sys
D = sys.argv[1]; HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "F1_CONSTRUCT_paper.md"), encoding="utf-8").read()


def img(path, alt, maxw=None):
    raw = open(path, "rb").read(); w, h = struct.unpack(">II", raw[16:24]); w //= 2
    if maxw:
        w = min(w, maxw)
    return f'<img alt="{alt}" width="{w}" src="data:image/png;base64,{base64.b64encode(raw).decode()}">'


k = [0]
def disp(m):
    k[0] += 1
    return f'<p align="center">{img(os.path.join(D, f"eq{k[0]}.png"), f"Equation {k[0]}", 760)}</p>'
out = re.sub(r"\$\$(.+?)\$\$", disp, src, flags=re.S)

INL = {
 r"1/N'": "1/N′",
 r"F_\beta = (1+\beta^2)\,|\cap| / (\beta^2|G_w(S)| + |G_w(Y)|)": "F<sub>β</sub> = (1+β²)·|∩| / (β²·|G<sub>w</sub>(S)| + |G<sub>w</sub>(Y)|)",
 r"G_w(Y)": "G<sub>w</sub>(Y)", r"G_w(Y^\star_i)": "G<sub>w</sub>(Y*<sub>i</sub>)", r"K = 8": "K = 8", "L": "L", "M": "M", "N": "N",
 r"N'": "N′", r"O(K\,M\,N')": "O(K·M·N′)", "P = R = 0": "P = R = 0", r"P(\text{Yes})": "P(Yes)", "S": "S", "S_0": "S<sub>0</sub>",
 r"S_1,\dots,S_N": "S<sub>1</sub>, …, S<sub>N</sub>", "U": "U", "U = 0": "U = 0", "Y": "Y", r"Y^\star \subset \mathcal{V}": "Y* ⊂ 𝒱",
 r"\bar P": "P̄", r"\bar P / \bar R": "P̄ / R̄", r"\bar R": "R̄",
 r"\beta \in \{0.5, 0.75, 1, 1.25, 1.5, 2, 2.5, 3, 4\}": "β ∈ {0.5, 0.75, 1, 1.25, 1.5, 2, 2.5, 3, 4}", r"\hat R": "R̂",
 r"\hat Y = \arg\max_{Y\in\{S_0,\dots,S_N\}}\hat R(Y)": "Ŷ = argmax over Y ∈ {S<sub>0</sub>, …, S<sub>N</sub>} of R̂(Y)",
 r"\mathbb E_{q}[U(Y,\cdot)]": "𝔼<sub>q</sub>[U(Y, ·)]", r"\mathcal W_S": "𝒲<sub>S</sub>",
 r"\partial F/\partial \bar R \,/\, \partial F/\partial \bar P = (\bar P/\bar R)^2": "(∂F/∂R̄) / (∂F/∂P̄) = (P̄/R̄)²",
 "d_0": "d<sub>0</sub>", r"d_1,\dots,d_N": "d<sub>1</sub>, …, d<sub>N</sub>", "i": "i", "l": "l", "q": "q", r"q \neq p": "q ≠ p",
 r"q(\cdot\mid x)": "q(· | x)", "w": "w", r"w \in \{1,\dots,5\}": "w ∈ {1, …, 5}", "x": "x"}
miss = []
def inl(m):
    t = m.group(1)
    if t not in INL:
        miss.append(t); return m.group(0)
    return "<i>" + INL[t] + "</i>" if len(INL[t]) <= 3 else INL[t]
out = re.sub(r"\$([^$\n]+?)\$", inl, out)
assert not miss, miss

FIG = {"figures/fig1_pipeline.svg": "fig1_pipeline", "figures/fig2_construct_steps.svg": "fig2_construct_steps",
       "figures/fig3_n_curve.svg": "fig3_n_curve", "figures/fig4_headroom.svg": "fig4_headroom"}
def fig(m):
    alt, p = m.group(1), m.group(2)
    return f'<p align="center">{img(os.path.join(D, FIG[p] + ".png"), alt)}</p>'
out = re.sub(r"!\[([^\]]*)\]\((figures/[^)]+)\)", fig, out)
out = out.replace("*Figures are generated by `reports/make_figures.py` from the aggregate numbers above.*",
                  "*Standalone build: formulas and figures are embedded as images (source: `reports/F1_CONSTRUCT_paper.md`, `reports/make_figures.py`).*")
first, rest = out.split("\n", 1)
out = first + " *(working title)*\n" + rest
open(os.path.join(HERE, "F1_CONSTRUCT_report_standalone.md"), "w", encoding="utf-8").write(out)
print("ok", len(out) // 1024, "KB; display formulas", k[0], "; dollar signs left:", out.count("$"))
